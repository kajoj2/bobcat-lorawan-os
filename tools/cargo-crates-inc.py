"""Write a BitBake <recipe>-crates.inc from a Cargo.lock.

Produces the same format as oe-core's `bitbake -c update_crates <recipe>`
(cargo-update-recipe-crates.bbclass), without needing a build host: one
crate:// SRC_URI entry and one sha256sum per crates.io package.

    tools/cargo-crates-inc.py Cargo.lock RECIPE > RECIPE-crates.inc
    tools/cargo-crates-inc.py https://raw.githubusercontent.com/o/r/TAG/Cargo.lock RECIPE > ...

Git and path dependencies are not supported (none of our recipes has them);
the script stops if it finds one.
"""
import sys
import tomllib
import urllib.request


def load(src):
    if src.startswith(("https://", "http://")):
        with urllib.request.urlopen(src) as r:
            return tomllib.loads(r.read().decode())
    with open(src, "rb") as f:
        return tomllib.load(f)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    lock = load(sys.argv[1])
    recipe = sys.argv[2]
    crates = []
    for pkg in lock.get("package", []):
        source = pkg.get("source")
        if source is None:
            continue  # workspace member
        if not source.startswith("registry+https://github.com/rust-lang/crates.io-index"):
            sys.exit(f"unsupported source for {pkg['name']}: {source}")
        crates.append((pkg["name"], pkg["version"], pkg["checksum"]))
    crates.sort()

    out = [f"# Autogenerated with 'tools/cargo-crates-inc.py' (same format as 'bitbake -c update_crates {recipe}')", "",
           "# from Cargo.lock", 'SRC_URI += " \\']
    out += [f"    crate://crates.io/{n}/{v} \\" for n, v, _ in crates]
    out.append('"')
    out.append("")
    out += [f'SRC_URI[{n}-{v}.sha256sum] = "{c}"' for n, v, c in crates]
    print("\n".join(out))


if __name__ == "__main__":
    main()
